#!/usr/bin/env python3
"""生成各方案“词库二字词条所在四码读音”清单（lua/mohu_<scheme>_word2_codes.lua）。

运行时（lua/mohu_express_translator.lua 0.18.0 组合让位规则）用它判定：
某个 4 键读音在 mohu_<scheme>.words 里有没有二字词条——有则该读音
不参与“非词单字组合让出首选给四码简词”（用户 2026-10-13 拍板：
读音有词一律不换，无论该词是不是首选）。

资产以 Lua 模块（require）分发而非数据文件：mira 等测试环境只把
编译产物放进用户目录，open_rime_file 找不到 lua/ 下的数据文件，
而 require 与其余 lua 模块走同一加载路径，两处都能命中。
模块缺失时运行时保守视为“处处有词”（不换，规则自动关闭）。

口径与 research/exports/export_clash_compose_blockers.py 一致：
text 恰 2 字、code 恰两个双拼音节（每段去 ;辅码 后为 2 个小写字母），
读音 = 两段拼接。**只收权重 > 0 的词条**（2026-10-13 用户拍板）：
moe/tencent 等外部导入的零权重语料残渣（昂日/阿蝉/甭来类）不算"读音有词"，
不参与组合让位守卫；零权重但真实的冷词（狼贪/孤鬼类）同样让位，其词条
仍在候选列表中，只是不再压四码简词。
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCHEMES = ("zrm", "flypy")


def extract_codes(words_dict: Path) -> set[str]:
    codes: set[str] = set()
    on = False
    for line in words_dict.read_text(encoding="utf-8").splitlines():
        if not on:
            if line == "...":
                on = True
            continue
        if not line or line.startswith("#"):
            continue
        cols = line.split("\t")
        if len(cols) < 3 or not cols[2].isdigit() or int(cols[2]) <= 0:
            continue
        if len(cols[0]) != 2:
            continue
        syls = [p.split(";")[0] for p in cols[1].split()]
        if len(syls) == 2 and all(len(s) == 2 and s.isalpha() and s.islower() for s in syls):
            codes.add(syls[0] + syls[1])
    return codes


def main() -> None:
    for scheme in SCHEMES:
        words_dict = ROOT / f"mohu_{scheme}.words.dict.yaml"
        codes = extract_codes(words_dict)
        out = ROOT / "lua" / f"mohu_{scheme}_word2_codes.lua"
        body = "-- generated by tools/gen_word2_codes.py (make dict); do not edit\n" \
            f"-- {scheme}: {len(codes)} 个带二字词条的四码读音，空格分隔单行返回\n" \
            'return "' + " ".join(sorted(codes)) + '"\n'
        out.write_text(body, encoding="utf-8")
        print(f"{scheme}: {len(codes)} codes -> {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
